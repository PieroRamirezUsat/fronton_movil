    primary = DarkPrimary,
    onPrimary = Color.Black,
    secondary = DarkTertiary,
    tertiary = DarkGold,
    background = DarkBackground,
    surface = DarkSurface,
    error = Color(0xFFFF6B6B),
)

/**
 * Un solo sistema de tema. El claro replica exactamente los tokens usados en las
 * pantallas diseñadas en Stitch; el oscuro es un fallback coherente con la misma
 * marca (Stitch no diseñó dark mode para esta app).
 */
@Composable
fun Aplicacion_FrontonTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colorScheme = if (darkTheme) DarkColors else LightColors

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as Activity).window
            window.statusBarColor = colorScheme.background.toArgb()
            WindowCompat.getInsetsController(window, view).isAppearanceLightStatusBars = !darkTheme
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
